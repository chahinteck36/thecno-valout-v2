export function getTemplateBySlug(slugOrId: string): StoreTemplate | undefined {
  if (!slugOrId) return undefined;
  const clean = slugOrId.toLowerCase().trim();
  return DEFAULT_TEMPLATES.find(t => (t.slug && t.slug.toLowerCase() === clean) || t.id.toLowerCase() === clean);
}

export function getTemplatesByCategory(categorySlug: string): StoreTemplate[] {
  if (!categorySlug || categorySlug === 'all') return DEFAULT_TEMPLATES;
  const clean = categorySlug.toLowerCase().trim();
  return DEFAULT_TEMPLATES.filter(t => t.categorySlug && t.categorySlug.toLowerCase() === clean);
}
